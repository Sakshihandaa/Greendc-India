/**
 * Filter and query helper for All India Cities
 */
export function searchCities(query = '', stateFilter = 'All', tierFilter = 'All') {
  const q = query.trim().toLowerCase();
  return ALL_INDIA_CITIES.filter((city) => {
    const matchesQuery = !q ||
      city.name.toLowerCase().includes(q) ||
      city.state.toLowerCase().includes(q) ||
      city.dcEcosystem.toLowerCase().includes(q) ||
      city.highlight.toLowerCase().includes(q);

    const matchesState = stateFilter === 'All' || city.state.toLowerCase() === stateFilter.toLowerCase();
    const matchesTier = tierFilter === 'All' || city.tier.toLowerCase() === tierFilter.toLowerCase();

    return matchesQuery && matchesState && matchesTier;
  });
}

export function getTopCoolingCities(limit = 8) {
  return [...ALL_INDIA_CITIES]
    .sort((a, b) => b.freeCoolingHours - a.freeCoolingHours)
    .slice(0, limit);
}

export function getSubseaHubs() {
  return ALL_INDIA_CITIES.filter((c) => c.subseaLanding);
}

export function getLowWaterRiskCities() {
  return ALL_INDIA_CITIES.filter((c) => c.waterRisk === 'Low');
}
